import 'dotenv/config';
import express from 'express';
import cors from 'cors';
import {createServer} from 'node:http';
import {Server} from 'socket.io';
import type {ClientEvents,ServerEvents} from '../../shared/types/contracts.js';
import {registerSockets} from './handlers/socket.js';
import {MAP} from './game/rules.js';
const port=Number(process.env.PORT??3001);
if(!Number.isInteger(port)||port<1||port>65535)throw Error('Invalid PORT');
const origins=(process.env.CLIENT_ORIGIN??'http://localhost:5173').split(',').map(s=>s.trim());
const app=express();app.use(cors({origin:origins}));app.use(express.json({limit:'10kb'}));
app.get('/health',(_,res)=>res.json({ok:true,service:'among-us-server'}));
app.get('/map',(_,res)=>res.json(MAP));
const httpServer=createServer(app);
const io=new Server<ClientEvents,ServerEvents>(httpServer,{cors:{origin:origins},maxHttpBufferSize:10_000,transports:['websocket','polling']});
registerSockets(io);
httpServer.listen(port,()=>console.info(`Server listening at http://localhost:${port}`));
const stop=()=>{io.close();httpServer.close(()=>process.exit(0))};
process.on('SIGINT',stop);process.on('SIGTERM',stop);
